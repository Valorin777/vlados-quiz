#!/usr/bin/env node
// Renders firestore.rules.tmpl into firestore.rules (prod) and firestore.dev.rules (dev).
//
//   node tools/gen-rules.mjs                   write both files
//   node tools/gen-rules.mjs --check           exit 1 if either file is out of date
//   node tools/gen-rules.mjs --check --target dev|prod
//        predeploy hook (firebase.json / firebase.dev.json): also refuses to deploy when the CLI's
//        project ($GCLOUD_PROJECT) is not the one this rules file is meant for, so the dev rules
//        (which trust bot-admin@vlados.test) can never reach prod by a wrong --project.
//
// Template syntax: {{limitName}} → shared/fbconfig.json limits; the line containing
// /*@DEV_ADMIN@*/ becomes the dev-only admin clause (removed entirely for prod).

import { readFileSync, writeFileSync } from 'node:fs';
import { relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEV_BOT_ADMIN_EMAIL, DEV_PROJECT, FBCONFIG, ROOT, RULES } from './lib/fbproject.mjs';

const DEV_MARK = '/*@DEV_ADMIN@*/';

/** @param {'prod'|'dev'} env */
export function renderRules(env, template = readFileSync(RULES.template, 'utf8')) {
  const limits = FBCONFIG.limits;
  let out = template.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    if (!(key in limits)) throw new Error(`firestore.rules.tmpl: unknown placeholder {{${key}}}`);
    return String(limits[key]);
  });
  const lines = out.split('\n');
  const idx = lines.findIndex((l) => l.includes(DEV_MARK));
  if (idx < 0 || lines.filter((l) => l.includes(DEV_MARK)).length !== 1) {
    throw new Error(`firestore.rules.tmpl must contain exactly one ${DEV_MARK} line`);
  }
  if (env === 'dev') {
    const indent = /^\s*/.exec(lines[idx])?.[0] ?? '';
    // Belt and braces: even if this file were deployed to prod, a prod ID token has aud = the
    // prod project id, so the clause can never match there.
    lines[idx] =
      `${indent}// DEV ONLY: test admin for automated tests (see tools/dev-bot-admin.mjs).\n` +
      `${indent}|| (email == '${DEV_BOT_ADMIN_EMAIL}' && request.auth.token.get('aud', '') == '${DEV_PROJECT}')`;
  } else {
    lines.splice(idx, 1);
  }
  out = lines.join('\n');
  const header =
    `// GENERATED by tools/gen-rules.mjs from firestore.rules.tmpl for ${env.toUpperCase()} ` +
    `(${FBCONFIG.projects[env].projectId}). Do not edit — edit the template and run \`npm run rules:gen\`.\n`;
  return header + out;
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const ti = args.indexOf('--target');
  const target = ti >= 0 ? args[ti + 1] : null;
  if (target !== null && target !== 'prod' && target !== 'dev') throw new Error('--target must be prod or dev');

  if (target) {
    const deploying = process.env.GCLOUD_PROJECT;
    const expected = RULES[target].project;
    if (deploying && deploying !== expected) {
      console.error(
        `REFUSED: ${relative(ROOT, RULES[target].config)} holds the ${target} rules (for ${expected}), ` +
          `but the deploy targets ${deploying}. Use: node tools/deploy-rules.mjs ${deploying === DEV_PROJECT ? 'dev' : 'prod'}`,
      );
      process.exit(1);
    }
  }

  let stale = false;
  for (const env of /** @type {const} */ (['prod', 'dev'])) {
    const want = renderRules(env);
    const file = RULES[env].file;
    let have = null;
    try {
      have = readFileSync(file, 'utf8');
    } catch {
      have = null;
    }
    if (have === want) continue;
    if (check) {
      console.error(`${relative(ROOT, file)} is out of date — run: npm run rules:gen`);
      stale = true;
    } else {
      writeFileSync(file, want);
      console.log(`wrote ${relative(ROOT, file)}`);
    }
  }
  if (stale) process.exit(1);
  if (check) console.log('rules up to date');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
